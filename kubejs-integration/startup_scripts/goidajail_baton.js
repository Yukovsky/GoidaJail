// ============================================================================
//  GoidaJail — регистрация "дубинки правосудия" через KubeJS
// ============================================================================
//  Куда положить:  <модпак>/kubejs/startup_scripts/goidajail_baton.js
//  Этот файл должен быть и на СЕРВЕРЕ, и на КЛИЕНТАХ (он идёт в составе
//  модпака вместе с остальной папкой kubejs/). Тогда предмет существует на
//  обеих сторонах и клиентов не выкидывает, а сам мод GoidaJail клиенту НЕ нужен.
//
//  Предмет создаётся БЕЗ рецепта -> его невозможно скрафтить ни во что.
//  Его id 'kubejs:jail_baton' должен совпадать с настройкой GoidaJail
//  'batonItemId' (config/goidajail-server.toml). Если меняешь id здесь —
//  поменяй и там.
// ============================================================================

StartupEvents.registry('item', event => {
    event.create('jail_baton')
        .displayName('Дубинка правосудия')
        .tooltip('Ударьте нарушителя, чтобы посадить его в тюрьму')
        .texture('minecraft:item/blaze_rod') // ванильная текстура, свой .png не нужен
        .unstackable()                       // максимум 1 в стопке
        .rarity('epic')                      // фиолетовое имя
        .glow(true)                          // лёгкое свечение зачарования
})
